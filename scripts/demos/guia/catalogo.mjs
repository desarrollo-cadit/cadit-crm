/**
 * Catálogo de los mini-tutoriales de la guía.
 *
 * Es el CONTRATO de cobertura: cada pantalla (ruta de `src/app/**\/page.tsx`)
 * y cada capacidad de `src/lib/capabilities.ts` tiene que aparecer en al menos
 * un video. `tests/unit/guia-videos-cobertura.test.ts` lo exige: si alguien
 * agrega una pantalla o una capacidad y no la cubre acá, el test falla.
 *
 * Cada entrada:
 *   id         clave estable; es el nombre del archivo (`<id>.mp4`).
 *   grupo      sección de la guía donde se muestra.
 *   titulo     título corto del video.
 *   audiencia  "staff" | "profesor" | "alumno" | "publico".
 *   requiere   capacidades que debe tener quien ve el video en la guía del
 *              staff (todas). Vacío = cualquier miembro del equipo.
 *   rutas      pantallas que el video recorre (forma del filesystem, sin
 *              grupos de rutas: `/cohorts/[id]`).
 *   cubre      lo que se muestra y se hace: es el guion resumido y la lista de
 *              verificación al revisar el video.
 *   estado     "pendiente" | "grabado" | "oculta" (pantalla que existe pero no
 *              está en el menú).
 */

